"""Hyperparameter search on internal origins before the final test (plan 2.6.3).

``pcs tune`` evaluates, for each model of ``tuning.yaml``, its declared configuration and grid
points up to the declared budget on every ``origin_stride``-th development origin, with the same
rolling window, horizons and panel as internal validation. The candidate with the lowest mean
MASE on the series of the tuning channel is written to ``tuned.yaml``, which validation and the
inventory simulation then use. Candidates with any failed forecast are not eligible. The final
test stays sealed: only the development panel is read.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import pandas as pd
import yaml

from pcsforecast import __version__
from pcsforecast.config import (
    FrequencyName,
    FrequencyProtocol,
    ModelsConfig,
    ModelSpec,
    ProtocolConfig,
    Status,
    TunedConfig,
    TunedModel,
    TuningConfig,
    file_sha256,
    load_project_config,
)
from pcsforecast.manifest import verify_outputs
from pcsforecast.models.registry import build_model, model_params
from pcsforecast.paths import ProjectPaths
from pcsforecast.runner.engine import run_engine
from pcsforecast.runtime import environment_fingerprint
from pcsforecast.tuning.search import candidates, score

TUNED_FILE = "tuned.yaml"
TUNED_HEADER = "# Generated by `pcs tune` from tuning.yaml; do not edit by hand. Frozen in F8.\n"


class TuningInputError(RuntimeError):
    """The search cannot run on the current inputs."""


def tuned_params(paths: ProjectPaths, frequency: FrequencyName) -> dict[str, dict[str, float]]:
    """Selected hyperparameters of one frequency; empty when nothing was tuned."""
    if not (paths.configs / TUNED_FILE).is_file():
        return {}
    tuned = load_project_config(paths.configs, TunedConfig)
    return {name: dict(params) for name, params in tuned.frequencies.get(frequency, {}).items()}


def tuned_inputs(paths: ProjectPaths) -> dict[str, str]:
    """Hash of ``tuned.yaml`` for a run record (empty when the file does not exist)."""
    path = paths.configs / TUNED_FILE
    return {TUNED_FILE: file_sha256(path)} if path.is_file() else {}


def _spec(models_config: ModelsConfig, name: str) -> ModelSpec:
    for specs in models_config.families.values():
        for spec in specs:
            if spec.name == name:
                return spec
    raise TuningInputError(f"tuning.yaml names a model that models.yaml does not declare: {name}")


def write_tuned(
    paths: ProjectPaths,
    frequency: FrequencyName,
    selected: Mapping[str, Mapping[str, float]],
    source: str,
) -> None:
    """Replace the selection of one frequency in ``tuned.yaml``, keeping the others."""
    path = paths.configs / TUNED_FILE
    current = (
        load_project_config(paths.configs, TunedConfig)
        if path.is_file()
        else TunedConfig.model_validate({"status": "draft"})
    )
    if current.status is Status.FROZEN:
        raise TuningInputError(f"{path} is frozen: the selection cannot change")
    frequencies = {**current.frequencies, frequency: {k: dict(v) for k, v in selected.items()}}
    sources = {**current.sources, frequency: source}
    updated = TunedConfig(status=current.status, frequencies=frequencies, sources=sources)
    body = yaml.safe_dump(updated.model_dump(mode="json"), sort_keys=True, allow_unicode=True)
    path.write_text(TUNED_HEADER + body, encoding="utf-8")


@dataclass(frozen=True)
class _Search:
    """What every candidate is evaluated on: one frequency's panel, series and origins."""

    panel: pd.DataFrame
    series_ids: list[str]
    scored: set[str]
    protocol: FrequencyProtocol
    frequency: FrequencyName

    def model(
        self, spec: ModelSpec, tuned_model: TunedModel, seed: int
    ) -> tuple[list[dict[str, object]], dict[str, float], int]:
        """Score rows of every candidate, the selected parameters and the origins used."""
        rows: list[dict[str, object]] = []
        eligible: list[tuple[float, int, dict[str, float]]] = []
        origins = 0
        declared = model_params(spec, self.frequency)
        for index, params in enumerate(candidates(declared, tuned_model, seed)):
            model = build_model(spec, params)
            if model is None:
                raise TuningInputError(f"{spec.name} cannot be built on this host")
            engine = run_engine(self.panel, self.series_ids, [model], self.protocol)
            predictions = engine.predictions.assign(frequency=self.frequency)
            if not predictions.empty:
                origins = max(origins, int(predictions["origin"].nunique()))
            value, defined = score(predictions, self.scored)
            rows.append(
                {
                    "model": spec.name,
                    "candidate": index,
                    "params": json.dumps(params, sort_keys=True),
                    "mean_mase": value,
                    "series_horizons_scored": defined,
                    "failures": len(engine.failures),
                    "seconds": round(engine.seconds_by_model.get(spec.name, 0.0), 3),
                }
            )
            if not engine.failures:
                eligible.append((value, index, params))
        if not eligible:
            raise TuningInputError(f"every candidate of {spec.name} failed")
        return rows, min(eligible, key=lambda item: item[:2])[2], origins


def run_tuning(
    paths: ProjectPaths,
    frequency: FrequencyName,
    protocol: ProtocolConfig,
    models_config: ModelsConfig,
    config: TuningConfig,
) -> Path:
    """Search every model of ``config`` for one frequency and record the selection."""
    if frequency not in config.frequencies:
        raise TuningInputError(f"tuning.yaml declares no search for {frequency}")
    changed = verify_outputs(paths.series, paths.root)
    if changed:
        raise TuningInputError(f"series files differ from the series manifest: {changed}")
    panel_path = paths.series / "panel_development.parquet"
    panel = pd.read_parquet(panel_path)
    profile = pd.read_parquet(paths.series / "profile.parquet")
    selected = profile[(profile["frequency"] == frequency) & profile["selected"]]
    series_ids = selected["series_id"].tolist()
    scored = set(selected.loc[selected["channel"] == config.channel, "series_id"])
    stride = config.frequencies[frequency].origin_stride
    tuning_protocol = protocol.frequencies[frequency].model_copy(update={"origin_step": stride})
    frequency_panel = panel[panel["frequency"] == frequency]

    started = datetime.now(UTC)
    search = _Search(frequency_panel, series_ids, scored, tuning_protocol, frequency)
    rows: list[dict[str, object]] = []
    choice: dict[str, dict[str, float]] = {}
    origins = 0
    for name, tuned_model in config.models.items():
        spec = _spec(models_config, name)
        model_rows, choice[name], model_origins = search.model(spec, tuned_model, config.seed)
        rows.extend(model_rows)
        origins = max(origins, model_origins)
    finished = datetime.now(UTC)

    run_id = f"{started:%Y%m%dT%H%M%SZ}-{frequency}-tuning"
    out = paths.tuning / run_id
    out.mkdir(parents=True, exist_ok=False)
    table = pd.DataFrame(rows)
    table.to_parquet(out / "candidates.parquet", index=False)
    write_tuned(paths, frequency, choice, run_id)
    record = {
        "run_id": run_id,
        "mode": "hyperparameter_search",
        "frequency": frequency,
        "metric": config.metric,
        "channel": config.channel,
        "origin_stride": stride,
        "origins": origins,
        "series_trained": len(series_ids),
        "series_scored": len(scored),
        "candidates": {name: int((table["model"] == name).sum()) for name in config.models},
        "selected": choice,
        "package_version": __version__,
        "started_at": started.isoformat(timespec="seconds"),
        "finished_at": finished.isoformat(timespec="seconds"),
        "inputs": {
            "panel_development": file_sha256(panel_path),
            "protocol.yaml": file_sha256(paths.configs / "protocol.yaml"),
            "models.yaml": file_sha256(paths.configs / "models.yaml"),
            "tuning.yaml": file_sha256(paths.configs / "tuning.yaml"),
        },
        "test_span_used": False,
        "environment": environment_fingerprint(),
    }
    (out / "tuning.json").write_text(
        json.dumps(record, indent=2, ensure_ascii=False, default=str) + "\n", encoding="utf-8"
    )
    return out
