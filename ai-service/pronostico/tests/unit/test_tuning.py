from __future__ import annotations

from pathlib import Path

import pandas as pd
import pytest

from pcsforecast.config import ModelsConfig, TunedModel
from pcsforecast.models.registry import build_models, model_params
from pcsforecast.models.statistical import TSB
from pcsforecast.paths import ProjectPaths
from pcsforecast.tuning.run import TuningInputError, tuned_inputs, tuned_params, write_tuned
from pcsforecast.tuning.search import candidates, score


def test_candidates_start_with_the_declared_configuration() -> None:
    grid = TunedModel(grid={"alpha": [0.05, 0.1, 0.2]}, budget=5)
    assert candidates({"alpha": 0.1}, grid, seed=1) == [
        {"alpha": 0.1},
        {"alpha": 0.05},
        {"alpha": 0.2},
    ]
    product = TunedModel(grid={"a": [1.0, 2.0, 3.0], "b": [1.0, 2.0, 3.0]}, budget=4)
    sampled = candidates({}, product, seed=7)
    assert sampled[0] == {}
    assert len(sampled) == 4
    assert sampled == candidates({}, product, seed=7)  # seeded
    order = [(c["a"], c["b"]) for c in sampled[1:]]
    assert order == sorted(order)  # kept in grid order


def test_empty_grid_values_are_rejected() -> None:
    with pytest.raises(ValueError, match="empty grid values"):
        TunedModel(grid={"alpha": []}, budget=1)


def predictions(errors: dict[str, float]) -> pd.DataFrame:
    rows = []
    for series_id, error in errors.items():
        for origin in range(3):
            rows.append(
                {
                    "series_id": series_id,
                    "frequency": "weekly",
                    "model": "m",
                    "family": "f",
                    "horizon": 1,
                    "origin": origin,
                    "y_true": 1.0,
                    "y_hat": 1.0 + error,
                    "scale_mae": 1.0 if series_id != "flat" else 0.0,
                    "scale_mse": 1.0,
                }
            )
    return pd.DataFrame(rows)


def test_score_averages_defined_mase_of_the_scored_series() -> None:
    frame = predictions({"a": 1.0, "b": 3.0, "flat": 5.0, "other": 9.0})
    assert score(frame, {"a", "b", "flat"}) == (2.0, 2)
    assert score(frame, {"flat"}) == (float("inf"), 0)
    assert score(pd.DataFrame(), {"a"}) == (float("inf"), 0)


def test_tuned_file_round_trip_and_parameter_precedence(tmp_path: Path) -> None:
    paths = ProjectPaths(tmp_path)
    paths.configs.mkdir()
    assert tuned_params(paths, "weekly") == {}
    assert tuned_inputs(paths) == {}
    write_tuned(paths, "weekly", {"tsb": {"alpha_d": 0.2, "alpha_p": 0.05}}, "run-1")
    write_tuned(paths, "monthly", {"croston": {"alpha": 0.3}}, "run-2")
    write_tuned(paths, "weekly", {"tsb": {"alpha_d": 0.3, "alpha_p": 0.05}}, "run-3")
    assert tuned_params(paths, "weekly") == {"tsb": {"alpha_d": 0.3, "alpha_p": 0.05}}
    assert tuned_params(paths, "monthly") == {"croston": {"alpha": 0.3}}
    assert "tuned.yaml" in tuned_inputs(paths)
    text = (paths.configs / "tuned.yaml").read_text(encoding="utf-8")
    assert text.startswith("# Generated by `pcs tune`")
    assert "run-3" in text

    config = ModelsConfig.model_validate(
        {
            "status": "draft",
            "families": {
                "intermittent": [
                    {
                        "name": "tsb",
                        "params": {"alpha_d": 0.1, "alpha_p": 0.1},
                        "params_by_frequency": {"weekly": {"alpha_p": 0.2}},
                    }
                ]
            },
        }
    )
    spec = config.families["intermittent"][0]
    assert model_params(spec, None) == {"alpha_d": 0.1, "alpha_p": 0.1}
    assert model_params(spec, "weekly") == {"alpha_d": 0.1, "alpha_p": 0.2}
    weekly = build_models(config, "weekly", tuned_params(paths, "weekly"))
    assert weekly.params["tsb"] == {"alpha_d": 0.3, "alpha_p": 0.05}
    model = weekly.models[0]
    assert isinstance(model, TSB)
    assert (model.alpha_d, model.alpha_p) == (0.3, 0.05)


def test_frozen_selection_cannot_change(tmp_path: Path) -> None:
    paths = ProjectPaths(tmp_path)
    paths.configs.mkdir()
    (paths.configs / "tuned.yaml").write_text("status: frozen\n", encoding="utf-8")
    with pytest.raises(TuningInputError, match="frozen"):
        write_tuned(paths, "weekly", {"croston": {"alpha": 0.2}}, "run-1")
