function normalizeText(value: string) {
  return value
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ');
}

export function normalizeDepartamento(value: string) {
  const normalized = normalizeText(value);
  const key = normalized.toLowerCase();
  return departamentoAliases[key] ?? getDepartamentos().find((department) => department.toLowerCase() === key) ?? normalized;
}

export function getDepartamentos() {
  return Object.keys(departamentosPeru) as DepartamentoPeru[];
}

export function getProvinciasByDepartamento(departamento: string) {
  const normalized = normalizeDepartamento(departamento);
  return departamentosPeru[normalized as DepartamentoPeru] ? [...departamentosPeru[normalized as DepartamentoPeru]] : [];
}

function normalizeProvincia(value: string) {
  const normalized = normalizeText(value);
  return provinciaAliases[normalized.toLowerCase()] ?? normalized;
}

